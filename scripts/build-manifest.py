#!/usr/bin/env python3
"""Writes frontend/data/manifest.js (window.MM_MANIFEST) so the static site knows which files exist.
GitHub Pages cannot list folders, so the workflow runs this before publishing. Any file name and any
image format is supported. Adding a file to a folder and pushing is all that is needed.

  images : folder -> {base-name: real file name} for the page-image folders (any extension)
  dirs   : folder -> [{file, size}] for every Downloads section and the Photo Gallery folder"""
import json, os, re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'frontend')
IMG_EXT = {'.webp', '.jpg', '.jpeg', '.png', '.gif', '.avif', '.svg', '.bmp'}
EXTRA = [{'dir': 'images/mm-marriage-photos', 'kind': 'images'},      # Guidance > Photo Gallery > Photos
         {'dir': 'images/mm-community-couples', 'kind': 'images'},    # Community page couples
         {'dir': 'images/celebrities-photo', 'kind': 'images'},       # Home > Celebrities
         {'dir': 'images/mm-main-stream-photo', 'kind': 'images'}]    # Home > Main streams

cfg = json.load(open(os.path.join(ROOT, 'data', 'downloads.config.json'), encoding='utf-8'))

def natural(s):
    return [int(x) if x.isdigit() else x.lower() for x in re.split(r'(\d+)', s)]

def scan(sec):
    folder = os.path.join(ROOT, sec['dir'])
    items = []
    if os.path.isdir(folder):
        for name in sorted(os.listdir(folder), key=natural):
            path = os.path.join(folder, name)
            if not os.path.isfile(path) or name.startswith('.') or name.lower().startswith('readme'):
                continue
            if sec.get('file') and name != sec['file']:
                continue
            if sec.get('prefix') and not name.startswith(sec['prefix']):
                continue
            if sec.get('kind') == 'images' and os.path.splitext(name)[1].lower() not in IMG_EXT:
                continue
            items.append({'file': name, 'size': os.path.getsize(path)})
    return items

dirs = {s['dir']: scan(s) for s in cfg.get('sections', []) + EXTRA}

images = {}
for folder in ['images', 'images/home-page-images', 'images/about-page-images']:
    m = {}
    root_dir = os.path.join(ROOT, folder)
    if os.path.isdir(root_dir):
        for name in sorted(os.listdir(root_dir), key=natural):
            base, ext = os.path.splitext(name)
            if os.path.isfile(os.path.join(root_dir, name)) and ext.lower() in IMG_EXT:
                m.setdefault(base, name)
    images[folder] = m

out = os.path.join(ROOT, 'data', 'manifest.js')
with open(out, 'w', encoding='utf-8') as f:
    f.write('/* AUTO-GENERATED by scripts/build-manifest.py - do not edit */\n')
    f.write('window.MM_MANIFEST = ' + json.dumps({'images': images, 'dirs': dirs}, ensure_ascii=False, indent=1) + ';\n')
print('manifest written:', {k: len(v) for k, v in images.items()}, 'images;', {k: len(v) for k, v in dirs.items()})
